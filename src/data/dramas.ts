function buildEpisodeSubtitles(
  leadA: string,
  leadB: string,
  lines: [string, string, string, string, string, string],
): SubtitleCue[] {
  return [
    { startSec: 0.5, endSec: 4.5, speaker: leadA, text: lines[0] },
    { startSec: 4.8, endSec: 9.2, speaker: leadB, text: lines[1] },
    { startSec: 9.6, endSec: 14.0, speaker: leadA, text: lines[2] },
    { startSec: 14.4, endSec: 18.8, speaker: leadB, text: lines[3] },
    { startSec: 19.2, endSec: 23.6, speaker: leadA, text: lines[4] },
    { startSec: 24.0, endSec: 28.0, speaker: leadB, text: lines[5] },
  ];
}

function createEpisodes(
  leadA: string,
  leadB: string,
  accentTint: string,
  specs: Array<{
    title: string;
    synopsis: string;
    sceneMood: string;
    durationSec: number;
    lines: [string, string, string, string, string, string];
  }>,
): Episode[] {
  return specs.map((spec, idx) => ({
    number: idx + 1,
    title: spec.title,
    synopsis: spec.synopsis,
    sceneMood: spec.sceneMood,
    durationSec: spec.durationSec,
    accentTint,
    subtitles: buildEpisodeSubtitles(leadA, leadB, spec.lines),
  }));
}

